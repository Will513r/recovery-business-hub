<?php
// CLI only. tools/ sits in the webroot, so without this guard the script is
// reachable by URL and shells out to git on a plain GET.
if (PHP_SAPI !== 'cli') {
    http_response_code(404);
    exit;
}

/**
 * Generates sitemap-lastmod.php: a map of sitemap path => the date that page's own
 * file last changed, taken from git history.
 *
 * Why: sitemap.php stamped the current time on all 7 static pages, so every crawl said
 * they changed that minute (B15 in 06-Reference/google-search-rules.md). Google
 * discounts a lastmod it learns not to trust. Same fix as
 * C:\Dev\tdm\bin\gen-sitemap-lastmod.php. The server has no usable git at request
 * time, so dates are resolved here, offline, and the generated array is committed.
 *
 * Business pages and job pages are not in this map: their lastmod comes from the
 * database (created_at / approved_at), so a new listing needs nothing run. The home,
 * /businesses and /jobs pages are lists, so sitemap.php takes the newer of the date
 * here and the newest listing they show.
 *
 * Usage, from the repo root:   php tools/gen-sitemap-lastmod.php
 * Re-run it when a page's file changes, then commit sitemap-lastmod.php. Forgetting
 * leaves a date a little stale, which is far smaller than "everything changed now".
 */

chdir(__DIR__ . '/..');

function git_date(string $file): ?string
{
    if (!is_file($file)) return null;
    $out = trim((string) shell_exec('git log -1 --format=%cs -- ' . escapeshellarg($file) . ' 2>&1'));
    return preg_match('/^\d{4}-\d{2}-\d{2}$/', $out) ? $out : null;
}

$static = [
    '/'             => 'index.php',
    '/jobs'         => 'jobs.php',
    '/businesses'   => 'businesses.php',
    '/post-job'     => 'post-job.php',
    '/about'        => 'about.php',
    '/privacy'      => 'privacy.php',
    '/add-business' => 'add-business.php',
];

$map = [];
foreach ($static as $path => $file) {
    $d = git_date($file);
    if ($d) $map[$path] = $d;
}
ksort($map);

$out = "<?php\n// GENERATED by tools/gen-sitemap-lastmod.php. Do not edit by hand.\n"
     . "// path => date that page's file last changed (git history). See the script header.\n"
     . "return [\n";
foreach ($map as $path => $d) {
    $out .= '    ' . var_export($path, true) . ' => ' . var_export($d, true) . ",\n";
}
$out .= "];\n";
file_put_contents(__DIR__ . '/../sitemap-lastmod.php', $out);
fwrite(STDOUT, count($map) . " dates written, " . count(array_unique($map)) . " distinct\n");
